def icon(name: str, size: int = 16) -> str:
    body = PATHS[name]
    return (
        f'<svg width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
        f'stroke="currentColor" stroke-width="2" stroke-linecap="round" '
        f'stroke-linejoin="round" aria-hidden="true">{body}</svg>'
    )


def _mask(name: str) -> str:
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        'fill="none" stroke="black" stroke-width="2" stroke-linecap="round" '
        f'stroke-linejoin="round">{PATHS[name]}</svg>'
    )
    return f'url("data:image/svg+xml,{quote(svg)}")'


def sidebar_icon_css(items: list[tuple[str, str]]) -> str:
    rules = []
    for slug, name in items:
        mask = _mask(name)
        selectors = [f"a[href*='{slug}']::before"]
        if slug == "command-center":
            selectors.append("a[href='']::before")
            selectors.append("a[href='/']::before")
        joined = ", ".join(f"section[data-testid='stSidebar'] {selector}" for selector in selectors)
        rules.append(
            f"{joined} {{"
            "content:'';width:16px;height:16px;flex:none;background:currentColor;"
            f"-webkit-mask:{mask} center / contain no-repeat;"
            f"mask:{mask} center / contain no-repeat;}}"
        )
    return "\n".join(rules)
